// FONT_SMALL, for the titles, the help and the Morse letters, was drawn
// for the talkie: capitals and figures seven dots high, most four wide,
// small letters five high with a dot of descender; the figures are all
// four wide, and the nought is crossed, so as not to be read for an O in
// a callsign. The less common marks are the old 5x7 font's, trimmed.
//
// Each letter is its columns, left to right, the lowest bit the top row,
// how far the next letter begins, and how many blank columns before the
// first drawn. All of printable ASCII, from the space to the tilde;
// anything else is shown as a space.

